export function singular(label: string): string {
  if (label.endsWith('ies')) {
    return `${label.slice(0, -3)}y`;
  }
  return label.endsWith('s') && !label.endsWith('ss') ? label.slice(0, -1) : label;
}

function articled(label: string): string {
  return `${/^[aeiou]/i.test(label) ? 'an' : 'a'} ${label.toLowerCase()}`;
}

function counted(count: number, label: string): string {
  const word = label.toLowerCase();
  return count === 1 ? `1 ${singular(word)}` : `${count} ${word}`;
}

