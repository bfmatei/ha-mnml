import type { CarPart, Words } from './en.ts';

function feminine(name: string): CarPart {
  return { name, open: `${name} deschisă`, halfOpen: `${name} întredeschisă` };
}

function neuter(name: string): CarPart {
  return { name, open: `${name} deschis`, halfOpen: `${name} întredeschis` };
}

const RULES = new Intl.PluralRules('ro');

function counted(count: number, one: string, many: string): string {
  const rule = RULES.select(count);
  return rule === 'one' ? `${count} ${one}` : `${count} ${rule === 'other' ? 'de ' : ''}${many}`;
}

